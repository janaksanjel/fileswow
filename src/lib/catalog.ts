export function getToolBySlug(slug: string): ToolDef | undefined {
  return ALL_TOOLS.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: ToolCategory): ToolDef[] {
  return ALL_TOOLS.filter((t) => t.category === category);
}

export function getToolsBySubCategory(category: ToolCategory, subCategory: SubCategory): ToolDef[] {
  return ALL_TOOLS.filter((t) => t.category === category && t.subCategory === subCategory);
}

export function getRelatedTools(tool: ToolDef): ToolDef[] {
  return tool.relatedSlugs.map(getToolBySlug).filter(Boolean) as ToolDef[];
}

